/* Generates bit-exact Rust copies of the static tables of the reference C
   decoder (sources in c/dec).

   Build & run from the repository root (the C reference sources must be
   available under c/):
     cc -DBROTLI_BUILD_NO_RBIT -I. -Ic/include -o /tmp/gen_dec \
        rust/src/dec/gen_dec_tables.c c/common/[a-z]*.c c/dec/bit_reader.c \
        c/dec/prefix.c c/dec/state.c c/dec/static_init.c -lm
     /tmp/gen_dec > rust/src/dec/tables.rs

   BROTLI_BUILD_NO_RBIT makes huffman.c define its kReverseBits table (the
   "rbit" instruction path computes the very same values). */
#include <stdio.h>
#include <stdint.h>
#include <string.h>

/* Static tables live in these translation units. */
#include "c/dec/huffman.c"
#include "c/dec/decode.c"

static void emit_u8(const char* name, const uint8_t* v, size_t n) {
  size_t i;
  printf("pub static %s: [u8; %zu] = [", name, n);
  for (i = 0; i < n; ++i) printf("%s%u,", (i % 16) ? " " : "\n    ", v[i]);
  printf("\n];\n\n");
}

int main(void) {
  size_t i;
  int c;
  printf("// @generated by rust/src/dec/gen_dec_tables.c from the reference C\n");
  printf("// sources. Do not edit by hand.\n\n");
  printf("#![allow(clippy::all)]\n\n");
  printf("use super::prefix::CmdLutElement;\n\n");

  /* prefix_inc.h */
  printf("/// `kCmdLut` (prefix_inc.h).\n");
  printf("pub static K_CMD_LUT: [CmdLutElement; %d] = [\n",
         BROTLI_NUM_COMMAND_SYMBOLS);
  for (i = 0; i < BROTLI_NUM_COMMAND_SYMBOLS; ++i) {
    const CmdLutElement* e = &kCmdLut[i];
    printf("    CmdLutElement { insert_len_extra_bits: %u, copy_len_extra_bits: %u, "
           "distance_code: %d, context: %u, insert_len_offset: %u, "
           "copy_len_offset: %u },\n",
           e->insert_len_extra_bits, e->copy_len_extra_bits, e->distance_code,
           e->context, e->insert_len_offset, e->copy_len_offset);
  }
  printf("];\n\n");

  /* bit_reader.c */
  printf("/// `kBrotliBitMask` (bit_reader.c).\n");
  printf("pub static K_BROTLI_BIT_MASK: [u32; 33] = [");
  for (i = 0; i < 33; ++i) {
    printf("%s0x%08X,", (i % 6) ? " " : "\n    ", (uint32_t)kBrotliBitMask[i]);
  }
  printf("\n];\n\n");

  /* huffman.c */
  printf("/// `kReverseBits` (huffman.c).\n");
  emit_u8("K_REVERSE_BITS", kReverseBits, sizeof(kReverseBits));

  /* decode.c */
  printf("/// `kCodeLengthCodeOrder` (decode.c).\n");
  emit_u8("K_CODE_LENGTH_CODE_ORDER", kCodeLengthCodeOrder,
          sizeof(kCodeLengthCodeOrder));
  printf("/// `kCodeLengthPrefixLength` (decode.c).\n");
  emit_u8("K_CODE_LENGTH_PREFIX_LENGTH", kCodeLengthPrefixLength,
          sizeof(kCodeLengthPrefixLength));
  printf("/// `kCodeLengthPrefixValue` (decode.c).\n");
  emit_u8("K_CODE_LENGTH_PREFIX_VALUE", kCodeLengthPrefixValue,
          sizeof(kCodeLengthPrefixValue));
  printf("/// `kRingBufferWriteAheadSlack` (decode.c).\n");
  printf("pub const K_RING_BUFFER_WRITE_AHEAD_SLACK: usize = %u;\n\n",
         (unsigned)kRingBufferWriteAheadSlack);

  /* BrotliDecoderErrorString (decode.c): NUL-terminated strings, exactly as
     produced by the BROTLI_DECODER_ERROR_CODES_LIST macro. */
  printf("/// `BrotliDecoderErrorString` results for codes -31..=3 (index = code + 31);\n");
  printf("/// `None` means the C function returns \"INVALID\".\n");
  printf("pub static K_ERROR_STRINGS: [Option<&[u8]>; 35] = [\n");
  for (c = -31; c <= 3; ++c) {
    const char* s = BrotliDecoderErrorString((BrotliDecoderErrorCode)c);
    if (strcmp(s, "INVALID") == 0) {
      printf("    None,\n");
    } else {
      printf("    Some(b\"%s\\0\"),\n", s);
    }
  }
  printf("];\n\n");
  printf("pub static K_ERROR_STRING_INVALID: &[u8] = b\"%s\\0\";\n",
         BrotliDecoderErrorString((BrotliDecoderErrorCode)-1000));
  return 0;
}
