/* Generates bit-exact Rust copies of the static tables of the reference C
   implementation (common + encoder foundation).

   Build & run from the repository root (the C reference sources must be
   available under c/):
     cc -I. -Ic/include -o /tmp/gen rust/tools/gen_common_tables.c -lm
     /tmp/gen > rust/src/common/tables.rs
*/
#include <stdio.h>
#include <stdint.h>
#include <string.h>

#include "c/common/constants.c"
#include "c/common/context.c"
#include "c/common/transform.c"
#include "c/enc/fast_log.c"

static void emit_u8(const char* name, const uint8_t* v, size_t n) {
  size_t i;
  printf("pub static %s: [u8; %zu] = [", name, n);
  for (i = 0; i < n; ++i) printf("%s%u,", (i % 16) ? " " : "\n    ", v[i]);
  printf("\n];\n\n");
}

static void emit_u16(const char* name, const uint16_t* v, size_t n) {
  size_t i;
  printf("pub static %s: [u16; %zu] = [", name, n);
  for (i = 0; i < n; ++i) printf("%s%u,", (i % 12) ? " " : "\n    ", v[i]);
  printf("\n];\n\n");
}

static void emit_f64(const char* name, const double* v, size_t n) {
  size_t i;
  printf("pub static %s: [f64; %zu] = [", name, n);
  for (i = 0; i < n; ++i) {
    /* %a is exact; Rust has no hex-float literals, so print a round-trip
       decimal and verify it below. */
    printf("%s%.17e,", (i % 3) ? " " : "\n    ", v[i]);
  }
  printf("\n];\n\n");
}

int main(void) {
  size_t i;
  printf("// @generated by rust/tools/gen_common_tables.c from the reference C\n");
  printf("// sources. Do not edit by hand.\n\n");
  printf("#![allow(clippy::all)]\n\n");

  emit_u8("CONTEXT_LOOKUP_TABLE", _kBrotliContextLookupTable, 2048);
  printf("/// Value of [`CONTEXT_LOOKUP_TABLE`] usable in constant expressions.\n");
  printf("pub const CONTEXT_LOOKUP_TABLE_VALUE: [u8; 2048] = {\n");
  printf("    let mut t = [0u8; 2048];\n    let mut i = 0;\n");
  printf("    while i < 2048 {\n        t[i] = CONTEXT_LOOKUP[i];\n        i += 1;\n    }\n    t\n};\n");
  printf("const CONTEXT_LOOKUP: [u8; 2048] = [");
  {
    size_t j;
    for (j = 0; j < 2048; ++j) printf("%s%u,", (j % 16) ? " " : "\n    ", _kBrotliContextLookupTable[j]);
  }
  printf("\n];\n\n");

  printf("pub const PREFIX_CODE_RANGES: [(u16, u8); 26] = [");
  for (i = 0; i < 26; ++i) {
    printf("%s(%u, %u),", (i % 6) ? " " : "\n    ",
           _kBrotliPrefixCodeRanges[i].offset, _kBrotliPrefixCodeRanges[i].nbits);
  }
  printf("\n];\n\n");

  emit_u8("TRANSFORM_PREFIX_SUFFIX", (const uint8_t*)kPrefixSuffix,
          sizeof(kPrefixSuffix));
  emit_u16("TRANSFORM_PREFIX_SUFFIX_MAP", kPrefixSuffixMap,
           sizeof(kPrefixSuffixMap) / sizeof(kPrefixSuffixMap[0]));
  emit_u8("TRANSFORMS_DATA", kTransformsData, sizeof(kTransformsData));
  printf("pub const TRANSFORMS_CUTOFF: [i16; 10] = [");
  for (i = 0; i < 10; ++i) printf("%s%d", i ? ", " : "", kBrotliTransforms.cutOffTransforms[i]);
  printf("];\n\n");

  emit_f64("LOG2_TABLE", kBrotliLog2Table, BROTLI_LOG2_TABLE_SIZE);
  return 0;
}
