/* Generates bit-exact Rust copies of the static tables of
   c/enc/entropy_encode_static.h and of the file-static tables of
   c/enc/compress_fragment.c used by the Rust port (owner: worker "entropy").

   Build & run from the repository root (link all C sources except
   compress_fragment.c, which is #included below; "STAR" = the glob "*"):
     cc -I. -Ic/include -o /tmp/gen_ent rust/tools/gen_entropy_static_tables.c \
       c/common/STAR.c $(ls c/enc/STAR.c | grep -v compress_fragment.c) -lm
     /tmp/gen_ent > rust/src/enc/entropy_encode_static/tables.rs
*/
#include <stdio.h>
#include <stdint.h>
#include <string.h>

#include "c/enc/entropy_encode_static.h"

/* kCmdHistoSeed is file-static in compress_fragment.c. */
#include "c/enc/compress_fragment.c"

static void emit_u8(const char* name, const uint8_t* v, size_t n) {
  size_t i;
  printf("pub static %s: [u8; %zu] = [", name, n);
  for (i = 0; i < n; ++i) printf("%s%u,", (i % 16) ? " " : "\n    ", v[i]);
  printf("\n];\n\n");
}

static void emit_u16(const char* name, const uint16_t* v, size_t n) {
  size_t i;
  printf("pub static %s: [u16; %zu] = [", name, n);
  for (i = 0; i < n; ++i) printf("%s%u,", (i % 12) ? " " : "\n    ", v[i]);
  printf("\n];\n\n");
}

static void emit_u32(const char* name, const uint32_t* v, size_t n) {
  size_t i;
  printf("pub static %s: [u32; %zu] = [", name, n);
  for (i = 0; i < n; ++i) printf("%s%u,", (i % 12) ? " " : "\n    ", v[i]);
  printf("\n];\n\n");
}

static void emit_u64(const char* name, const uint64_t* v, size_t n) {
  size_t i;
  printf("pub static %s: [u64; %zu] = [", name, n);
  for (i = 0; i < n; ++i) {
    printf("%s0x%08llx,", (i % 6) ? " " : "\n    ", (unsigned long long)v[i]);
  }
  printf("\n];\n\n");
}

#define N(a) (sizeof(a) / sizeof((a)[0]))

int main(void) {
  printf("// @generated by rust/tools/gen_entropy_static_tables.c from the\n");
  printf("// reference C sources. Do not edit by hand.\n\n");
  printf("#![allow(clippy::all)]\n\n");
  emit_u8("K_CODE_LENGTH_DEPTH", kCodeLengthDepth, N(kCodeLengthDepth));
  emit_u8("K_STATIC_COMMAND_CODE_DEPTH", kStaticCommandCodeDepth,
          N(kStaticCommandCodeDepth));
  emit_u8("K_STATIC_DISTANCE_CODE_DEPTH", kStaticDistanceCodeDepth,
          N(kStaticDistanceCodeDepth));
  emit_u32("K_CODE_LENGTH_BITS", kCodeLengthBits, N(kCodeLengthBits));
  emit_u64("K_ZERO_REPS_BITS", kZeroRepsBits, N(kZeroRepsBits));
  emit_u32("K_ZERO_REPS_DEPTH", kZeroRepsDepth, N(kZeroRepsDepth));
  emit_u64("K_NON_ZERO_REPS_BITS", kNonZeroRepsBits, N(kNonZeroRepsBits));
  emit_u32("K_NON_ZERO_REPS_DEPTH", kNonZeroRepsDepth, N(kNonZeroRepsDepth));
  emit_u16("K_STATIC_COMMAND_CODE_BITS", kStaticCommandCodeBits,
           N(kStaticCommandCodeBits));
  emit_u16("K_STATIC_DISTANCE_CODE_BITS", kStaticDistanceCodeBits,
           N(kStaticDistanceCodeBits));
  emit_u32("K_CMD_HISTO_SEED", kCmdHistoSeed, N(kCmdHistoSeed));
  return 0;
}
