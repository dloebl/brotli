/* Generates bit-exact Rust copies of the encoder static dictionary lookup
   tables of the reference C implementation.

   Build & run from the repository root:
     cc -I. -Ic/include -o /tmp/gen2 rust/tools/gen_enc_dict_tables.c
     /tmp/gen2 > rust/src/enc/static_dict_tables.rs
*/
#include <stdio.h>
#include <stdint.h>

#include "c/enc/dictionary_hash.c"
#include "c/enc/static_dict_lut.c"

int main(void) {
  size_t i;
  printf("// @generated by rust/tools/gen_enc_dict_tables.c from the reference C\n");
  printf("// sources. Do not edit by hand.\n\n");
  printf("#![allow(clippy::all)]\n\n");
  printf("use super::static_dict_lut::DictWord;\n\n");
  printf("pub static STATIC_DICTIONARY_HASH_WORDS: [u16; %d] = [", BROTLI_ENC_NUM_HASH_BUCKETS);
  for (i = 0; i < BROTLI_ENC_NUM_HASH_BUCKETS; ++i)
    printf("%s%u,", (i % 16) ? " " : "\n    ", kStaticDictionaryHashWords[i]);
  printf("\n];\n\n");
  printf("pub static STATIC_DICTIONARY_HASH_LENGTHS: [u8; %d] = [", BROTLI_ENC_NUM_HASH_BUCKETS);
  for (i = 0; i < BROTLI_ENC_NUM_HASH_BUCKETS; ++i)
    printf("%s%u,", (i % 24) ? " " : "\n    ", kStaticDictionaryHashLengths[i]);
  printf("\n];\n\n");
  printf("pub static STATIC_DICTIONARY_BUCKETS: [u16; %d] = [", BROTLI_ENC_STATIC_DICT_LUT_NUM_BUCKETS);
  for (i = 0; i < BROTLI_ENC_STATIC_DICT_LUT_NUM_BUCKETS; ++i)
    printf("%s%u,", (i % 16) ? " " : "\n    ", kStaticDictionaryBuckets[i]);
  printf("\n];\n\n");
  printf("macro_rules! w { ($l:expr, $t:expr, $i:expr) => { DictWord { len: $l, transform: $t, idx: $i } }; }\n\n");
  printf("pub static STATIC_DICTIONARY_WORDS: [DictWord; %d] = [", BROTLI_ENC_STATIC_DICT_LUT_NUM_ITEMS);
  for (i = 0; i < BROTLI_ENC_STATIC_DICT_LUT_NUM_ITEMS; ++i)
    printf("%sw!(%u, %u, %u),", (i % 6) ? " " : "\n    ",
           kStaticDictionaryWords[i].len, kStaticDictionaryWords[i].transform,
           kStaticDictionaryWords[i].idx);
  printf("\n];\n");
  return 0;
}
